def fetch_user_profile_context(user_id_or_username: str = None) -> dict:
    """
    Connects to MongoDB and retrieves user's declared interests, liked reels history,
    and profile metadata to condition Qwen 2.5:7b prompt generation.
    """
    context = {
        "user_id": None,
        "username": None,
        "interests": [],
        "liked_reels": [],
        "liked_topics": [],
    }
    if MongoClient is None:
        return context

    try:
        client = MongoClient(
            MONGO_URI,
            tlsCAFile=certifi.where() if certifi else None,
            serverSelectionTimeoutMS=4000,
            tlsAllowInvalidCertificates=True,
        )
        db = client[DB_NAME]

        # 1. Fetch user by id or username if specified, else most active user
        user_doc = None
        if user_id_or_username:
            from bson import ObjectId
            if ObjectId.is_valid(user_id_or_username):
                user_doc = db["users"].find_one({"_id": ObjectId(user_id_or_username)})
            if not user_doc:
                user_doc = db["users"].find_one({"$or": [{"username": user_id_or_username}, {"user_id": user_id_or_username}]})

        if not user_doc:
            user_doc = db["users"].find_one({}, sort=[("updatedAt", -1)])

        if user_doc:
            context["user_id"] = str(user_doc.get("_id"))
            context["username"] = user_doc.get("username")
            context["interests"] = [str(i).strip() for i in user_doc.get("interests", []) if str(i).strip()]

        # 2. Fetch liked reels from MongoDB
        query = {}
        if context["user_id"]:
            query["liked_by"] = context["user_id"]

        liked_cursor = db["reels"].find(query).sort("likes_count", -1).limit(6)
        for r in liked_cursor:
            context["liked_reels"].append({
                "title": r.get("title"),
                "topic": r.get("topic"),
                "caption": r.get("caption"),
                "video_prompt": r.get("video_prompt"),
            })
            if r.get("topic") and r.get("topic") not in context["liked_topics"]:
                context["liked_topics"].append(r.get("topic"))

        # If no user-specific likes found, fetch top liked reels overall
        if not context["liked_reels"]:
            top_liked = db["reels"].find({"likes_count": {"$gt": 0}}).sort("likes_count", -1).limit(4)
            for r in top_liked:
                context["liked_reels"].append({
                    "title": r.get("title"),
                    "topic": r.get("topic"),
                    "caption": r.get("caption"),
                })

    except Exception as e:
        pass

    return context


def _clean_json_response(raw: str) -> str:
    cleaned = raw.strip()
    if cleaned.startswith("```"):
        cleaned = cleaned.strip("`")
        cleaned = cleaned.replace("json", "", 1).strip()
    return cleaned


def generate_reel_spec(topic: str, sub_angle: str = "", user_context: dict = None) -> dict:
    """
    Returns {"video_prompt": str, "negative_prompt": str, "caption": str}.
    Uses Qwen 2.5:7b to synthesize a customized photorealistic Wan 2.2 prompt
    and factual caption conditioned on the user's declared interests and liked history.
    """
    user_message_parts = [f"Topic to direct: '{topic}'"]
    if sub_angle:
        user_message_parts.append(f"Sub-Angle / Specific Focus: {sub_angle}")

    if user_context:
        interests = user_context.get("interests", [])
        liked_reels = user_context.get("liked_reels", [])
        username = user_context.get("username")

        if username:
            user_message_parts.append(f"Target User Profile: @{username}")
        if interests:
            user_message_parts.append(f"User's Declared Interests: {', '.join(interests)}")
        if liked_reels:
            liked_summary = "; ".join([f"'{r.get('title')}' ({r.get('topic')})" for r in liked_reels[:4]])
            user_message_parts.append(f"Content User Previously Liked & Enjoyed: {liked_summary}")

        user_message_parts.append(
            "Personalization Directive: Deeply personalize this scene's cinematography, subject details, "
            "and factual hook to resonate with the user's interests and favorite visual styles."
        )

    user_message = "\n".join(user_message_parts)

    try:
        response = ollama.chat(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_message},
            ],
        )
        raw_content = response["message"]["content"]
        cleaned = _clean_json_response(raw_content)
        data = json.loads(cleaned)

        if "video_prompt" not in data or "caption" not in data:
            raise ValueError("Missing expected keys in model output")

        return {
            "video_prompt": data["video_prompt"],
            "negative_prompt": data.get(
                "negative_prompt",
                "morphing, warping, distorted faces, flickering, extra limbs, text, watermark",
            ),
            "caption": data["caption"],
        }

    except Exception as e:
        print(f"[generate_reel_spec] Failed for topic '{topic}': {e}")
        subject_desc = sub_angle if sub_angle else f"active live-action details of {topic}"
        return {
            "video_prompt": (
                f"8K photorealistic IMAX live-action documentary footage, smooth low-angle tracking push-in shot of {subject_desc}, "
                "authentic physical material textures, sharp optical focus, directional key sunlight with volumetric atmospheric haze, "
                "shot on 35mm cinema lens, accompanied by immersive realistic ambient sound design and environment audio"
            ),
            "negative_prompt": (
                "cartoon, drawing, sketch, illustration, anime, 3D render, CGI animation, painting, concept art, "
                "doodle, artificial look, blurry, morphing, distorted anatomy, flickering, watermark, text overlay, low resolution, static image"
            ),
            "caption": f"A crucial scientific and historical milestone in {topic} that reshaped human understanding.",
        }


