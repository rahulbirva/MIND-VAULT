def run_batch(force: bool = False, target_topic: str = None, target_user: str = None):
    """
    Loops through topics, calls Ollama to engineer prompt & caption
    tailored to the user's interests and liked reels, checks disk for existing files,
    and generates videos with Wan 2.2 / fallback.
    """
    ensure_dirs()
    manifest = load_manifest()
    manifest_by_filename = {item.get("filename"): item for item in manifest}

    user_context = fetch_user_profile_context(target_user)

    prompts_to_process = REEL_PROMPTS
    if target_topic:
        prompts_to_process = [p for p in REEL_PROMPTS if p["topic"].lower() == target_topic.lower()][:1]
        if not prompts_to_process:
            prompts_to_process = [REEL_PROMPTS[0]]

    print("=" * 70)
    print(f"🎬  MindVault AI Reels — Video Generation Pipeline (Wan 2.2: {QUANT_LABEL})")
    print(f"🤖  LLM Model: {MODEL_NAME} | WanGP API: {WANGP_API_URL}")
    if user_context.get("username") or user_context.get("interests"):
        print(f"👤  Personalized for: @{user_context.get('username') or 'User'}")
        print(f"🎯  User Interests: {', '.join(user_context.get('interests', [])) or 'General Knowledge'}")
        print(f"❤️   Liked History  : {len(user_context.get('liked_reels', []))} reel(s)")
    print(f"📁  Output Directory: {OUTPUT_DIR}")
    print(f"📋  Total Target Reels: {len(prompts_to_process)}")
    if force:
        print("⚡  Force Re-generation: ENABLED (overwriting existing files)")
    print("=" * 70)

    batch_start = time.time()
    generated_count = 0
    skipped_count = 0

    topic_counts: dict[str, int] = {}

    for i, item in enumerate(prompts_to_process, 1):
        topic = item["topic"]
        title = item["title"]
        sub_angle = item.get("sub_angle") or item.get("prompt", "")

        topic_counts[topic] = topic_counts.get(topic, 0) + 1
        filename = f"{topic}_{topic_counts[topic]}.mp4"
        output_path = os.path.join(OUTPUT_DIR, filename)

        print(f"\n[{i}/{len(prompts_to_process)}] Topic: '{topic}' | Title: '{title}'")
        print(f"  Target File: {filename}")

        # Resumability check
        file_exists = os.path.exists(output_path) and os.path.getsize(output_path) > 1024

        if file_exists and not force:
            print(f"  ⏭️  Already generated on disk ({os.path.getsize(output_path) / 1024:.1f} KB). Skipping video generation.")
            skipped_count += 1

            # Check if existing manifest entry lacks caption or video_prompt; if so, populate it
            existing_entry = manifest_by_filename.get(filename)
            if not existing_entry or not existing_entry.get("caption") or not existing_entry.get("video_prompt"):
                spec = generate_reel_spec(topic, sub_angle=sub_angle, user_context=user_context)
                manifest = [m for m in manifest if m.get("filename") != filename]
                manifest.append({
                    "topic": topic,
                    "filename": filename,
                    "title": title,
                    "caption": spec["caption"],
                    "video_prompt": spec["video_prompt"],
                    "negative_prompt": spec["negative_prompt"],
                    "createdAt": (existing_entry and existing_entry.get("createdAt")) or time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                })
                manifest_by_filename[filename] = manifest[-1]
                save_manifest(manifest)
            continue

        # 1. Generate customized prompt with Qwen 2.5:7b based on user interests
        spec = generate_reel_spec(topic, sub_angle=sub_angle, user_context=user_context)

        # 2. Print video_prompt, negative_prompt, and caption BEFORE starting video generation
        print(f"  🎬 Video Prompt    : {spec['video_prompt']}")
        print(f"  🚫 Negative Prompt : {spec['negative_prompt']}")
        print(f"  💬 Caption         : {spec['caption']}")

        # 3. Pass video_prompt and negative_prompt to video generation calls
        clip_start = time.time()
        print(f"  ⚡ Generating 5s clip with Wan 2.2 ({WIDTH}x{HEIGHT}, {QUANT_LABEL}) / fallback...")

        gen_success = False

        # Attempt 1: Local WanGP server
        gen_success = try_generate_with_wangp(
            spec["video_prompt"],
            output_path,
            negative_prompt=spec["negative_prompt"]
        )

        # Attempt 2: Local high-fidelity procedural fallback
        if not gen_success:
            print("  ℹ️  Local WanGP server unavailable — generating high-fidelity local cinematic video fallback...")
            generate_procedural_reel(topic, title, spec["video_prompt"], output_path)

        clip_elapsed = time.time() - clip_start
        file_size_kb = os.path.getsize(output_path) / 1024 if os.path.exists(output_path) else 0
        print(f"  ✅ Finished in {clip_elapsed:.2f}s | Size: {file_size_kb:.1f} KB")

        # Step 3: Update manifest with { topic, filename, title, caption, video_prompt }
        manifest = [m for m in manifest if m.get("filename") != filename]
        manifest.append({
            "topic": topic,
            "filename": filename,
            "title": title,
            "caption": spec["caption"],
            "video_prompt": spec["video_prompt"],
            "negative_prompt": spec["negative_prompt"],
            "createdAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        })
        manifest_by_filename[filename] = manifest[-1]
        save_manifest(manifest)
        generated_count += 1

    total_elapsed = time.time() - batch_start
    print("\n" + "=" * 70)
    print("🎉  AI REELS BATCH COMPLETED")
    print(f"📊  Generated: {generated_count} | Skipped: {skipped_count} | Total: {len(prompts_to_process)}")
    print(f"⏱️   Total Batch Time: {total_elapsed:.2f}s")
    print(f"📄  Manifest File Saved to: {MANIFEST_PATH}")
    print("=" * 70)


