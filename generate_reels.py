def load_manifest() -> list[dict]:
    if os.path.exists(MANIFEST_PATH):
        try:
            with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
                if isinstance(data, list):
                    return data
        except Exception as e:
            print(f"⚠️ Warning reading manifest ({e}), starting fresh.")
    return []


def save_manifest(manifest: list[dict]):
    with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    sync_manifest_to_mongodb(manifest)


def sync_reel_to_mongodb(reel_data: dict) -> bool:
    """
    Upserts a single reel document into MongoDB 'reels' collection.
    """
    if MongoClient is None:
        return False
    try:
        client = MongoClient(
            MONGO_URI,
            tlsCAFile=certifi.where() if certifi else None,
            serverSelectionTimeoutMS=4000,
            tlsAllowInvalidCertificates=True,
        )
        db = client[DB_NAME]
        filename = reel_data.get("filename")
        if not filename:
            return False

        doc = {
            "topic": reel_data.get("topic"),
            "filename": filename,
            "title": reel_data.get("title"),
            "caption": reel_data.get("caption", ""),
            "video_prompt": reel_data.get("video_prompt", ""),
            "negative_prompt": reel_data.get("negative_prompt", ""),
            "videoUrl": f"/generated_reels/{filename}",
            "duration": 5.0,
            "aspectRatio": "9:16",
            "resolution": f"{WIDTH}x{HEIGHT}",
            "model": f"Wan 2.2 ({QUANT_LABEL} GGUF)",
            "updatedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }

        db["reels"].update_one(
            {"filename": filename},
            {
                "$set": doc,
                "$setOnInsert": {
                    "likes_count": 0,
                    "views_count": 0,
                    "liked_by": [],
                    "createdAt": reel_data.get("createdAt") or doc["updatedAt"],
                },
            },
            upsert=True,
        )
        return True
    except Exception as e:
        return False


def sync_manifest_to_mongodb(manifest: list[dict]) -> int:
    """
    Syncs the entire manifest list into MongoDB 'reels' collection.
    """
    if MongoClient is None or not manifest:
        return 0
    synced_count = 0
    for item in manifest:
        if sync_reel_to_mongodb(item):
            synced_count += 1
    if synced_count > 0:
        print(f"  💾 [MongoDB] Synchronized {synced_count}/{len(manifest)} reel(s) to '{DB_NAME}.reels'")
    return synced_count


def try_generate_with_wangp(prompt: str, output_path: str, negative_prompt: str = "") -> bool:
    """
    Attempts to call a running local WanGP Gradio server endpoint (http://127.0.0.1:7860).
    Payload matches Wan 2.2 text-to-video Gradio API:
    - prompt: str
    - negative_prompt: str
    - width: 720
    - height: 1280
    - num_frames: 120 (5 seconds @ 24fps)
    - fps: 24
    - quant: "q6_k"
    - seed: 42
    Returns True if video successfully retrieved and written to output_path, False otherwise.
    """
    try:
        url = f"{WANGP_API_URL.rstrip('/')}/api/predict"
        payload = {
            "data": [
                prompt,
                negative_prompt or (
                    "cartoon, drawing, sketch, illustration, anime, 3D render, CGI animation, painting, concept art, "
                    "doodle, artificial look, blurry, morphing, distorted anatomy, flickering, watermark, text overlay, low resolution, static image"
                ),
                WIDTH,
                HEIGHT,
                TOTAL_FRAMES,
                FPS,
                QUANT_SETTING,
                42,
            ]
        }
        print(f"  [WanGP] Calling local Wan 2.2 API at {url} ({WIDTH}x{HEIGHT}, {QUANT_LABEL})...")
        resp = requests.post(url, json=payload, timeout=600)
        if resp.status_code == 200:
            result = resp.json()
            video_data = result.get("data", [None])[0]
            if video_data and isinstance(video_data, dict) and "name" in video_data:
                file_url = f"{WANGP_API_URL.rstrip('/')}/file={video_data['name']}"
                v_resp = requests.get(file_url, timeout=60)
                if v_resp.status_code == 200:
                    with open(output_path, "wb") as f:
                        f.write(v_resp.content)
                    print(f"  [WanGP] Video generated and saved from Wan 2.2 to: {output_path}")
                    return True
        print(f"  [WanGP] WanGP endpoint returned HTTP {resp.status_code} or unexpected payload format.")
        return False
    except Exception as e:
        print(f"  [WanGP Info] Local WanGP server not reachable ({e}). Falling back to high-fidelity synthesizer.")
        return False



def generate_procedural_reel(topic: str, title: str, prompt: str, output_path: str):
    """
    High-fidelity procedural video generator.
    Creates a full 5-second (120 frames at 24fps) 720x1280 720p MP4 video
    with theme-specific cinematic visuals:
    - space: starry cosmos with camera drift, glowing nebulae, rising rocket & smoke particles.
    - history: golden sunset sky, silhouette colosseum arches with depth, drifting dust motes.
    - politics: neoclassical pillars, patriotic banner ripple, majestic lighting rays.
    - technology: glowing circuit board with pulsing electrical impulses.
    - science: glowing biological neural network with branching synapses.
    """
    frames = []
    sx = WIDTH / 480.0
    sy = HEIGHT / 864.0

    # Pre-generate particle seeds for consistency
    rng = random.Random(abs(hash(title)) % 1000000)
    stars = [(rng.randint(0, WIDTH), rng.randint(0, HEIGHT), rng.uniform(1.2 * sx, 4.0 * sx), rng.uniform(0, math.pi * 2)) for _ in range(240)]
    dust = [(rng.randint(0, WIDTH), rng.randint(0, HEIGHT), rng.uniform(2.0 * sx, 5.0 * sx), rng.uniform(-1, 1), rng.uniform(-1.5, 0.5)) for _ in range(80)]
    circuits = [
        [(rng.randint(int(20 * sx), WIDTH - int(20 * sx)), rng.randint(int(50 * sy), HEIGHT - int(120 * sy))),
         (rng.randint(int(20 * sx), WIDTH - int(20 * sx)), rng.randint(int(50 * sy), HEIGHT - int(120 * sy))),
         (rng.randint(int(20 * sx), WIDTH - int(20 * sx)), rng.randint(int(50 * sy), HEIGHT - int(120 * sy)))]
        for _ in range(16)
    ]

    for frame_idx in range(TOTAL_FRAMES):
        t = frame_idx / FPS  # 0.0 to 5.0 seconds
        progress = frame_idx / TOTAL_FRAMES

        img = Image.new("RGB", (WIDTH, HEIGHT), color=(15, 23, 42))
        draw = ImageDraw.Draw(img)

        # ── Visual themes ──────────────────────────────────────────────────────────
        if topic == "space":
            # Space Theme: Deep cosmic background with star parallax and rocket ascent
            for y in range(HEIGHT):
                ratio = y / HEIGHT
                r = int(6 + 18 * ratio)
                g = int(8 + 12 * ratio)
                b = int(22 + 45 * ratio)
                draw.line([(0, y), (WIDTH, y)], fill=(r, g, b))

            # Nebula clouds
            nebula_pulse = 0.5 + 0.5 * math.sin(t * 1.5)
            nebula_color = (int(60 * nebula_pulse), int(20 * nebula_pulse), int(90 * nebula_pulse))
            draw.ellipse([int(60 * sx), int(180 * sy), int(420 * sx), int(560 * sy)], fill=nebula_color)

            # Starfield with twinkle & subtle pan
            for sx_p, sy_p, s_size, s_phase in stars:
                twinkle = 0.6 + 0.4 * math.sin(t * 3.0 + s_phase)
                cur_y = (sy_p - t * 18) % HEIGHT
                col = int(220 * twinkle)
                draw.ellipse([sx_p, cur_y, sx_p + s_size, cur_y + s_size], fill=(col, col, int(min(255, col + 30))))

            # Rocket Ascent
            rocket_y = HEIGHT - int(320 * sy) - int(progress * 520 * sy)
            rocket_x = WIDTH // 2

            # Smoke plume & fiery thrust
            flame_len = (50 + 20 * math.sin(t * 20)) * sy
            draw.polygon([
                (rocket_x - int(16 * sx), rocket_y + int(45 * sy)),
                (rocket_x + int(16 * sx), rocket_y + int(45 * sy)),
                (rocket_x, rocket_y + int(45 * sy) + flame_len)
            ], fill=(255, int(140 + 40 * math.sin(t * 15)), 20))
            draw.polygon([
                (rocket_x - int(8 * sx), rocket_y + int(45 * sy)),
                (rocket_x + int(8 * sx), rocket_y + int(45 * sy)),
                (rocket_x, rocket_y + int(45 * sy) + flame_len * 0.6)
            ], fill=(255, 240, 180))

            # Smoke particles
            for i in range(22):
                sp_y = rocket_y + int(60 * sy) + i * int(16 * sy) + int(math.sin(i + t * 4) * 10)
                if sp_y < HEIGHT:
                    sp_w = int((24 + i * 6) * sx)
                    sp_alpha = max(0, 180 - i * 8)
                    draw.ellipse([rocket_x - sp_w, sp_y, rocket_x + sp_w, sp_y + int(28 * sy)], fill=(sp_alpha, sp_alpha, sp_alpha + 15))

            # Rocket body
            draw.rounded_rectangle([rocket_x - int(18 * sx), rocket_y, rocket_x + int(18 * sx), rocket_y + int(48 * sy)], radius=int(5 * sx), fill=(240, 244, 248))
            draw.polygon([(rocket_x - int(18 * sx), rocket_y), (rocket_x + int(18 * sx), rocket_y), (rocket_x, rocket_y - int(32 * sy))], fill=(225, 29, 72))
            draw.polygon([(rocket_x - int(18 * sx), rocket_y + int(24 * sy)), (rocket_x - int(34 * sx), rocket_y + int(48 * sy)), (rocket_x - int(18 * sx), rocket_y + int(48 * sy))], fill=(225, 29, 72))
            draw.polygon([(rocket_x + int(18 * sx), rocket_y + int(24 * sy)), (rocket_x + int(34 * sx), rocket_y + int(48 * sy)), (rocket_x + int(18 * sx), rocket_y + int(48 * sy))], fill=(225, 29, 72))

        elif topic == "history":
            # History Theme: Golden Sunset over Classical Colosseum silhouette
            for y in range(HEIGHT):
                ratio = y / HEIGHT
                r = int(180 * (1 - ratio * 0.7))
                g = int(90 * (1 - ratio * 0.6))
                b = int(45 * (1 - ratio * 0.5))
                draw.line([(0, y), (WIDTH, y)], fill=(r, g, b))

            # Sun disc
            sun_y = int(340 * sy) - int(progress * 50 * sy)
            draw.ellipse([WIDTH // 2 - int(80 * sx), sun_y - int(80 * sy), WIDTH // 2 + int(80 * sx), sun_y + int(80 * sy)], fill=(255, 210, 130))

            # Colosseum / Monument silhouette
            colosseum_color = (25, 18, 14)
            base_y = int(520 * sy)
            draw.rectangle([int(20 * sx), base_y, WIDTH - int(20 * sx), HEIGHT - int(140 * sy)], fill=colosseum_color)
            for arch_idx in range(6):
                ax = int(45 * sx) + arch_idx * int(68 * sx)
                draw.chord([ax, base_y + int(30 * sy), ax + int(48 * sx), base_y + int(115 * sy)], 180, 360, fill=(160, 80, 40))
                draw.chord([ax, base_y + int(130 * sy), ax + int(48 * sx), base_y + int(205 * sy)], 180, 360, fill=(160, 80, 40))

            # Floating golden dust motes
            for i, (dx, dy, dsize, vx, vy) in enumerate(dust):
                cur_x = (dx + t * vx * 14) % WIDTH
                cur_y = (dy + t * vy * 14) % HEIGHT
                pulse = 0.5 + 0.5 * math.sin(t * 2 + i)
                val = int(220 * pulse)
                draw.ellipse([cur_x, cur_y, cur_x + dsize, cur_y + dsize], fill=(val, int(val * 0.8), int(val * 0.4)))

